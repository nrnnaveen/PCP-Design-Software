export const footprintLibrary = {
  getAllFootprints: (): FootprintDefinition[] => {
    return BUILTIN_FOOTPRINTS;
  },
  getFootprint: (idOrName?: string): FootprintDefinition | undefined => {
    if (!idOrName) return undefined;
    const q = idOrName.toLowerCase();
    return BUILTIN_FOOTPRINTS.find(
      (f) => f.id.toLowerCase() === q || f.name.toLowerCase() === q || f.id.toLowerCase().endsWith(':' + q)
    );
  },
};

